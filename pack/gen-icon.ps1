# gen-icon.ps1 - turn MouseMeter.ico into a C# byte literal.
#
#   powershell -NoProfile -ExecutionPolicy Bypass -File .\pack\gen-icon.ps1
#
# Why generate instead of commit a 117 KB source file: the .ico is already in the repo
# and is already generated from IconFactory. A checked-in copy of its bytes is a third
# copy of the same data that can silently drift. Generating it at build time means the
# icon inside the exe is always the current MouseMeter.ico, by construction.
#
# Output: pack\obj\IconResource.cs (gitignored - it is a build artifact)

param(
    [string]$Root = (Split-Path $PSScriptRoot -Parent)
)

$ErrorActionPreference = 'Stop'

$icoPath = Join-Path $Root 'MouseMeter.ico'
if (-not (Test-Path $icoPath)) { throw ('missing icon: ' + $icoPath) }

$bytes = [System.IO.File]::ReadAllBytes($icoPath)

$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine('// <auto-generated>')
[void]$sb.AppendLine('//   Produced by pack\gen-icon.ps1 from MouseMeter.ico. Do not edit.')
[void]$sb.AppendLine('// </auto-generated>')
[void]$sb.AppendLine('using System;')
[void]$sb.AppendLine('using System.Drawing;')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('namespace MouseMeter')
[void]$sb.AppendLine('{')
[void]$sb.AppendLine('    internal static class AppIconBytes')
[void]$sb.AppendLine('    {')
[void]$sb.AppendLine('        internal const int Length = ' + $bytes.Length + ';')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('        internal static byte[] Read()')
[void]$sb.AppendLine('        {')
[void]$sb.AppendLine('            return new byte[]')
[void]$sb.AppendLine('            {')

for ($i = 0; $i -lt $bytes.Length; $i += 16) {
    $end = [Math]::Min($i + 16, $bytes.Length)
    $row = @()
    for ($j = $i; $j -lt $end; $j++) { $row += ('0x' + $bytes[$j].ToString('x2')) }
    [void]$sb.AppendLine('                ' + ($row -join ', ') + ',')
}

[void]$sb.AppendLine('            };')
[void]$sb.AppendLine('        }')
[void]$sb.AppendLine('    }')
[void]$sb.AppendLine('}')

$outDir = Join-Path $PSScriptRoot 'obj'
New-Item -ItemType Directory -Force -Path $outDir | Out-Null
$outPath = Join-Path $outDir 'IconResource.cs'
[System.IO.File]::WriteAllText($outPath, $sb.ToString(), (New-Object System.Text.UTF8Encoding $false))

Write-Host ('  ' + $outPath + ' (' + $bytes.Length + ' icon bytes, ' + (Get-Item $outPath).Length + ' chars of C#)')
